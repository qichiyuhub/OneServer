#!/bin/bash
#
# 把面板历史刷到盘上
#
# 只由 oneserver-web-slow.service 在采集之后调用，不是用户命令 —— 没有 @command，
# 因此不进注册表、不进菜单。把它列进菜单会诱导用户手动跑一个没有任何交互、
# 也没有任何可看输出的内部步骤。
#
# ==================================================================
# 为什么它不能待在采集器里
# ==================================================================
#
# 采集器（web_collect.sh）是 `root-nolock`：每 3 到 30 秒一轮，**不持锁**。
# 不持锁是它敢这么高频跑的全部前提 —— 每一轮都去抢全局锁的话，用户敲的真实
# 命令会随机撞上等待（实测别的进程持锁 5 秒时，一条普通 root 命令等了 3767ms）。
# 而规范给这一档的代价很明确：零系统副作用。写盘是副作用。
#
# 所以持久化只能交给一个**持锁的**进程，也就是这个文件。
#
# 跟慢档（5 分钟）而不是跟快档（30 秒）：跟快档就是每 30 秒重写一次 99 KB，
# 那正是把 public/ 搬到 tmpfs 要消掉的那笔写入。代价只是最多丢最后 5 分钟曲线。
#
# ==================================================================
# 为什么是 root-trylock
# ==================================================================
#
# 这一轮刷不刷都行，晚 5 分钟没有代价 —— 正是规范给 `root-trylock` 划的那一档：
# 有副作用，但晚一轮无所谓。拿不到锁就以 0 退出，**不记成失败**：用户在菜单里
# 停留期间锁一直被占，把它记成错误会让 JSONL 每轮多几条，而那份日志正是面板
# 自己要发布的产物。
#
# @privilege    root-trylock
# @requires_lib >= 4.1

set -Eeuo pipefail
IFS=$'\n\t'
PATH='/usr/sbin:/usr/bin:/sbin:/bin'
export PATH
umask 027

source /opt/oneserver/lib/bootstrap.sh

main() {
    local src="${OS_PUBLIC_DIR}/${OS_WEB_HISTORY_NAME}"

    # 采集器还没写出第一份，或者刚重启 tmpfs 是空的 —— 都不是错，下一轮就有了
    [[ -r ${src} ]] || return 0

    # 这里**不 mkdir** 目标目录：它由 install.sh 与切换器建，而 unit 的
    # ReadWritePaths 精确列了它 —— 真要是不存在，systemd 在 ExecStart 之前就以
    # 226/NAMESPACE 失败了，那是一条看得见的错误，比这里静默补建再静默降级好。
    #
    # 内容没变就不写（os::install_file 换 inode 的语义与 os::write_public 一致），
    # 机器闲着时这个文件一天也不会动一次。
    #
    # `--quiet`：这条每 5 分钟跑一次，默认的 info 级会在 JSONL 里堆出一天 288 条
    # 例行记录，把真实事件挤出面板日志页 —— 而那份日志正是面板自己要发布的产物。
    os::install_file --quiet --mode 0640 "${src}" "${OS_WEB_HISTORY_FILE}" || return 0

    os::debug '面板历史已刷到盘上'
    return 0
}

main "$@"
